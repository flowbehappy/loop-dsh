import {readFileSync, writeFileSync} from "node:fs"
import {resolve} from "node:path"
import {fileURLToPath} from "node:url"

// The Desktop Exec export is the cross-module contract. This projection never
// maintains a separate set of Task field definitions in the plugin.
export function deriveDispatchSchema(actions) {
  const canonical = actions.find(action => action.id === "task.create")?.inputSchema
  const richItem = canonical?.properties?.tasks?.oneOf?.find(branch =>
    branch.items?.properties?.assignee !== undefined)?.items
  if (!richItem) throw new Error("Canonical task.create rich item is unavailable")
  const properties = Object.fromEntries(["title", "description", "assignee"].map(name => {
    const field = richItem.properties[name]
    if (field?.type !== "string") throw new Error(`Canonical task.create ${name} changed`)
    return [name, structuredClone(field)]
  }))
  properties.assignee.minLength = 1
  properties.assignee.description = "Exact memberId from collaboration_directory; required for tracked delegation."
  return {
    type: "object", additionalProperties: false, required: ["tasks"],
    properties: {tasks: {
      type: "array", minItems: 1, maxItems: 1,
      description: "Exactly one Task. Host supplies the bound channel and acceptance identity. Use separate accepted operations for separate Tasks.",
      items: {type: "object", additionalProperties: false, properties, required: ["title", "assignee"]},
    }},
  }
}

export function renderDispatchSchema(actions) {
  return `// Generated from Loop Desktop Exec task.create by generate-collaboration-schema.mjs.\n// Edit the canonical owner or generator, then regenerate; do not edit this file.\nexport const dispatchTaskSchema = ${JSON.stringify(deriveDispatchSchema(actions), null, 2)}\n`
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const root = process.argv[2] ?? process.env.LOOP_SOURCE_ROOT
  if (!root) throw new Error("Supply LOOP_SOURCE_ROOT or the Loop source directory")
  const actions = JSON.parse(readFileSync(resolve(root, "internal/actioncontract/default_actions.json"), "utf8"))
  writeFileSync(new URL("./collaboration-task-schema.mjs", import.meta.url), renderDispatchSchema(actions))
}
